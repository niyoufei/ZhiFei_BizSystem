def _normalized_name(name: str) -> str:
    normalized = unicodedata.normalize("NFKC", name).strip().casefold()
    return re.sub(r"[\W_]+", "", normalized, flags=re.UNICODE)


def _catalog_id(theme: str, name: str) -> str:
    identity = f"{theme}:{_normalized_name(name)}"
    return hashlib.sha256(identity.encode("utf-8")).hexdigest()


def catalog_entries(scene_tag: str) -> list[CatalogEntry]:
    """Return a fresh, ordered list of catalog entries for one scene."""

    try:
        scene = PROJECT_TYPE_CATALOGS[scene_tag]
    except KeyError as exc:
        raise KeyError(f"unknown project scene tag: {scene_tag}") from exc

    themes = scene["themes"]
    assert isinstance(themes, dict)
    entries: list[CatalogEntry] = []
    for theme in THEME_ORDER:
        pairs = themes[theme]
        assert isinstance(pairs, tuple)
        for code, name in pairs:
            entries.append(
                {
                    "catalog_id": _catalog_id(theme, name),
                    "code": code,
                    "name": name,
                    "theme": theme,
                    "scene_tag": scene_tag,
                }
            )
    return entries


def catalog_total(scene_tag: str) -> int:
    """Return the number of catalog entries for one scene."""

    return len(catalog_entries(scene_tag))


def combined_catalog_entries(scene_tags: Iterable[str]) -> list[CatalogEntry]:
    """Return an ordered, catalog-id-deduplicated union for multiple scenes."""

    if isinstance(scene_tags, str):
        scene_tags = (scene_tags,)

    seen: set[str] = set()
    combined: list[CatalogEntry] = []
    for scene_tag in scene_tags:
        for entry in catalog_entries(scene_tag):
            catalog_id = entry["catalog_id"]
            if catalog_id in seen:
                continue
            seen.add(catalog_id)
            combined.append(entry)
    return combined
